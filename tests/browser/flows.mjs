// UI flow checks: MyPLAYER builder, pause menu, box score, substitutions,
// halftime and final screens (simulation fast-forwarded between captures).
import { chromium } from 'playwright-core';
import { startServer } from './server.mjs';
import fs from 'node:fs';
import path from 'node:path';
const out = path.resolve('tests/browser/out');
fs.mkdirSync(out, { recursive: true });
const exe = fs.readdirSync('/opt/pw-browsers').map((d) => `/opt/pw-browsers/${d}/chrome-linux/chrome`).find((p) => fs.existsSync(p));
const server = await startServer(5195);
const browser = await chromium.launch({ executablePath: exe, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errs = [];
page.on('pageerror', (e) => errs.push(String(e.stack || e)));
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
const shot = (n) => page.screenshot({ path: path.join(out, `${n}.png`), timeout: 180000 });
await page.goto(server.url);
await page.evaluate(() => { localStorage.setItem('hw27.settings', JSON.stringify({ quality: 'low', replays: false })); });
await page.reload();
await page.waitForSelector('.main-nav', { timeout: 60000 });
await page.click('[data-go="builder"]');
await page.waitForTimeout(6000);
await shot('f-builder');
await page.click('[data-a="save"]');
await page.click('[data-a="back"]');
await page.click('[data-go="playnow"]');
await page.click('[data-opt="quarterMin"][data-v="3"]');
await page.click('[data-a="start"]');
await page.waitForSelector('.pregame', { timeout: 240000 });
await page.keyboard.press('Enter');
await page.waitForFunction(() => window.__app.game.running && window.__app.game.sim.match.phase !== 'pregame', null, { timeout: 60000 });
await page.evaluate(() => { const g = window.__app.game; g.paused = true; g.fastForward(60); g.paused = false; g.setPaused(true); });
await page.waitForTimeout(2500);
await shot('f-pause');
await page.click('[data-a="box"]');
await page.waitForTimeout(1500);
await shot('f-box');
await page.click('[data-a="back"]');
await page.click('[data-a="subs"]');
await page.waitForTimeout(1500);
await shot('f-subs');
await page.click('[data-a="back"]');
await page.click('[data-a="resume"]');
await page.evaluate(() => { const g = window.__app.game; g.fastForward(600, (sim) => sim.match.phase === 'halftime'); g.hud.update(0.016); });
await page.waitForTimeout(2500);
await shot('f-halftime');
await page.click('[data-a="go"]');
await page.evaluate(() => { const g = window.__app.game; g.settings.replays = false; g.fastForward(900, (sim) => sim.match.phase === 'final'); });
await page.waitForTimeout(5000);
await shot('f-final');
const res = await page.evaluate(() => { const m = window.__app.game.sim.match; return { phase: m.phase, q: m.quarter, score: m.score, finalShown: !!document.querySelector('.overlay.final') }; });
console.log(JSON.stringify(res));
console.log('errors', errs.slice(0, 10));
await browser.close();
await server.close();
