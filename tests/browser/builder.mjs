import { launchBrowser } from './launch.mjs';
import { startServer } from './server.mjs';
import fs from 'node:fs';
process.chdir('/home/user/Game');
const server = await startServer(5194);
const browser = await launchBrowser();
const page = await browser.newPage({ viewport: { width: 1440, height: 810 } });
await page.goto(server.url);
await page.waitForSelector('.main-nav', { timeout: 60000 });
await page.click('[data-go="builder"]');
await page.waitForTimeout(9000);
await page.screenshot({ path: '/home/user/Game/tests/browser/out/f-builder.png', timeout: 120000 });
await browser.close();
await server.close();
